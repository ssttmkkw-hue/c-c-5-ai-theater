export function normLine(text) {
  return String(text || '')
    .toLowerCase()
    .replace(/['’]/g, '')
    .replace(/[^a-z0-9\u3400-\u9fff]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

export function translateLine(text) {
  const key = normLine(text);
  return LINE_ZH[key] || null;
}

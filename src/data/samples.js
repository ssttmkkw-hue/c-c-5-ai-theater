import { normLine, translateLine } from './translations.js';

export { normLine };

export function applyTranslations(performance) {
  if (!performance) return performance;
  for (const scene of performance.scenes || []) {
    for (const beat of scene.beats || []) {
      if (!beat.line || beat.lineZh) continue;
      const zh = translateLine(beat.line);
      if (zh) beat.lineZh = zh;
    }
  }
  return performance;
}

export function listSamples() {
  return Object.values(samples);
}

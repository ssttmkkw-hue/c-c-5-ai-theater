export function t(lang, key) {
  const pack = STR[lang] || STR.zh;
  return pack[key] ?? STR.en[key] ?? key;
}

export function formatWarning(lang, code) {
  const text = String(code || '');
  const pair = (prefix, key) => (text.startsWith(prefix) ? t(lang, key) + text.slice(prefix.length) : null);
  return (
    pair('new-character:', 'newCharacter')
    || pair('unknown-direction:', 'unknownDirection')
    || pair('skipped:', 'skipped')
    || pair('unknown-emotion:', 'unknownEmotion')
    || pair('unknown-gesture:', 'unknownGesture')
    || pair('unknown-mark:', 'unknownMark')
    || pair('unknown-costume:', 'unknownCostume')
    || (text === 'ai-fallback-no-backend' ? t(lang, 'aiFallback') : null)
    || (text === 'ai-fallback-error' ? t(lang, 'aiFallbackErr') : null)
    || (text === 'no-cues' ? t(lang, 'noCues') : null)
    || (text === 'json-invalid' ? t(lang, 'jsonInvalid') : null)
    || (text === 'empty-performance' ? t(lang, 'emptyPerformance') : null)
    || text
  );
}
